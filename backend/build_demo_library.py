"""Generate data/demo_library (procedural arches + catalogue) and data/samples/proc_upper_01 (per-tooth OBJ case folder)."""
import json
from pathlib import Path

from dental_reg import library, procedural

root = Path(__file__).resolve().parents[1] / "data"
lib = root / "demo_library"
lib.mkdir(parents=True, exist_ok=True)
models = []
for seed in range(1, 21):
    n = 7 if seed % 5 == 0 else 6  # a few 14-tooth arches
    a = procedural.make_arch(seed, "upper", n)
    mid = f"upper_proc{seed:02d}"
    library.save_arch_npz(a, lib / f"{mid}.npz")
    e = library.build_entry(a, mid, f"{mid}.npz")
    e["source"], e["license"] = "Procedurally generated by this project (not anatomical)", "Project licence (original work)"
    e["preprocessing"] = "procedural, per-tooth labelled, npz"
    models.append(e)
for seed in (101, 102):
    a = procedural.make_arch(seed, "lower", 6)
    mid = f"lower_proc{seed}"
    library.save_arch_npz(a, lib / f"{mid}.npz")
    e = library.build_entry(a, mid, f"{mid}.npz")
    e["source"], e["license"] = "Procedurally generated by this project (not anatomical)", "Project licence (original work)"
    models.append(e)
(lib / "catalogue.json").write_text(json.dumps({"schema": "dental-library/1", "models": models}, indent=1))
procedural.write_case_dir(procedural.make_arch(1, "upper", 6, name="proc_upper_01"), root / "samples" / "proc_upper_01")
print(len(models), "models;", sum(e["classification"] == "complete_arch" for e in models), "complete")
